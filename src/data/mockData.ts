// Default India financial year (1 April – 31 March) derived from today's date
// so it stays configurable rather than permanently hard-coded.
export function defaultFinancialYear(): FinancialYearSettings {
  const now = new Date();
  const year = now.getMonth() >= 3 ? now.getFullYear() : now.getFullYear() - 1;
  return {
    id: `fy-${year}-${year + 1}`,
    name: `Financial Year ${year}-${String(year + 1).slice(2)}`,
    startDate: new Date(year, 3, 1).toISOString(),
    endDate: new Date(year + 1, 2, 31, 23, 59, 59).toISOString(),
  };
}

